library ieee;
use ieee.std_logic_1164.all;

entity Shift_Register_4_str_vhdl_tb is
end Shift_Register_4_str_vhdl_tb;

architecture Behavioral of Shift_Register_4_str_vhdl_tb is

    signal t_s0      : std_logic := '0';
    signal t_s1      : std_logic := '0';
    signal t_MSB_in  : std_logic := '0';
    signal t_LSB_in  : std_logic := '0';
    signal t_clk     : std_logic := '0';
    signal t_Clear_b : std_logic := '0';

    signal t_I_par   : std_logic_vector(3 downto 0) := "0000";
    signal t_A_par   : std_logic_vector(3 downto 0);

begin

    ------------------------------------------------------------
    -- DUT
    ------------------------------------------------------------
    UUT : entity work.Shift_Register_4_str_vhdl
        port map (
            s0      => t_s0,
            s1      => t_s1,
            MSB_in  => t_MSB_in,
            LSB_in  => t_LSB_in,
            clk     => t_clk,
            Clear_b => t_Clear_b,
            I_par   => t_I_par,
            A_par   => t_A_par
        );

    ------------------------------------------------------------
    -- Clock Generation
    -- Clock Period = 10 ns
    ------------------------------------------------------------
    clock_process : process
    begin
        while now < 160 ns loop
            t_clk <= '0';
            wait for 5 ns;

            t_clk <= '1';
            wait for 5 ns;
        end loop;

        wait;
    end process;

    ------------------------------------------------------------
    -- Stimulus
    ------------------------------------------------------------
    stimulus_process : process
    begin

        --------------------------------------------------------
        -- Initial Clear
        --------------------------------------------------------
        t_Clear_b <= '0';
        t_s0      <= '0';
        t_s1      <= '0';
        t_MSB_in  <= '0';
        t_LSB_in  <= '0';
        t_I_par   <= "0000";

        wait for 10 ns;

        --------------------------------------------------------
        -- Parallel Load
        -- 11 -> 1010
        --------------------------------------------------------
        t_Clear_b <= '1';
        t_s0      <= '1';
        t_s1      <= '1';
        t_I_par   <= "1010";

        wait for 10 ns;

        --------------------------------------------------------
        -- Hold
        -- 00 -> 1010
        --------------------------------------------------------
        t_s0 <= '0';
        t_s1 <= '0';

        wait for 10 ns;

        --------------------------------------------------------
        -- Shift Right
        -- 1010 -> 0101
        --------------------------------------------------------
        t_s0     <= '0';
        t_s1     <= '1';
        t_MSB_in <= '0';

        wait for 10 ns;

        --------------------------------------------------------
        -- Shift Right
        -- 0101 -> 1010
        --------------------------------------------------------
        t_MSB_in <= '1';

        wait for 10 ns;

        --------------------------------------------------------
        -- Parallel Load
        -- 11 -> 1100
        --------------------------------------------------------
        t_s0    <= '1';
        t_s1    <= '1';
        t_I_par <= "1100";

        wait for 10 ns;

        --------------------------------------------------------
        -- Shift Left
        -- 1100 -> 1001
        --------------------------------------------------------
        t_s0     <= '1';
        t_s1     <= '0';
        t_LSB_in <= '1';

        wait for 10 ns;

        --------------------------------------------------------
        -- Shift Left
        -- 1001 -> 0010
        --------------------------------------------------------
        t_LSB_in <= '0';

        wait for 10 ns;

        --------------------------------------------------------
        -- Hold
        -- 00 -> 0010
        --------------------------------------------------------
        t_s0 <= '0';
        t_s1 <= '0';

        wait for 10 ns;

        --------------------------------------------------------
        -- Asynchronous Clear
        -- 0010 -> 0000
        --------------------------------------------------------
        t_Clear_b <= '0';

        wait for 5 ns;

        --------------------------------------------------------
        -- Release Clear
        --------------------------------------------------------
        t_Clear_b <= '1';

        --------------------------------------------------------
        -- Parallel Load
        -- 11 -> 0110
        --------------------------------------------------------
        t_s0    <= '1';
        t_s1    <= '1';
        t_I_par <= "0110";

        wait for 10 ns;

        --------------------------------------------------------
        -- End
        --------------------------------------------------------
        wait;

    end process;

end Behavioral;
