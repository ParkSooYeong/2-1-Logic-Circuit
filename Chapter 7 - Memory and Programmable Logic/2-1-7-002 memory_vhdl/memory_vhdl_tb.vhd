library ieee;
use ieee.std_logic_1164.all;

entity memory_vhdl_tb is
end memory_vhdl_tb;

architecture Behavioral of memory_vhdl_tb is

    signal t_Enable    : std_logic := '0';
    signal t_ReadWrite : std_logic := '0';

    signal t_DataIn    : std_logic_vector(3 downto 0) := "0000";
    signal t_Address   : std_logic_vector(5 downto 0) := "000000";

    signal t_DataOut   : std_logic_vector(3 downto 0);

begin

    ------------------------------------------------------------
    -- DUT
    ------------------------------------------------------------
    UUT : entity work.memory_vhdl
        port map (
            Enable    => t_Enable,
            ReadWrite => t_ReadWrite,
            DataIn    => t_DataIn,
            Address   => t_Address,
            DataOut   => t_DataOut
        );

    ------------------------------------------------------------
    -- Stimulus
    ------------------------------------------------------------
    stimulus_process : process
    begin

        --------------------------------------------------------
        -- Initial State
        --------------------------------------------------------
        t_Enable    <= '0';
        t_ReadWrite <= '0';
        t_Address   <= "000000";
        t_DataIn    <= "0000";

        wait for 10 ns;

        --------------------------------------------------------
        -- Write Address 0
        -- Mem[0] = 1010
        --------------------------------------------------------
        t_Enable    <= '1';
        t_ReadWrite <= '0';
        t_Address   <= "000000";
        t_DataIn    <= "1010";

        wait for 10 ns;

        --------------------------------------------------------
        -- Write Address 1
        -- Mem[1] = 1100
        --------------------------------------------------------
        t_Address <= "000001";
        t_DataIn  <= "1100";

        wait for 10 ns;

        --------------------------------------------------------
        -- Write Address 10
        -- Mem[10] = 0110
        --------------------------------------------------------
        t_Address <= "001010";
        t_DataIn  <= "0110";

        wait for 10 ns;

        --------------------------------------------------------
        -- Read Address 0
        -- Expected: 1010
        --------------------------------------------------------
        t_ReadWrite <= '1';
        t_Address   <= "000000";

        wait for 10 ns;

        --------------------------------------------------------
        -- Read Address 1
        -- Expected: 1100
        --------------------------------------------------------
        t_Address <= "000001";

        wait for 10 ns;

        --------------------------------------------------------
        -- Read Address 10
        -- Expected: 0110
        --------------------------------------------------------
        t_Address <= "001010";

        wait for 10 ns;

        --------------------------------------------------------
        -- Disable Memory
        -- Expected: ZZZZ
        --------------------------------------------------------
        t_Enable <= '0';

        wait for 10 ns;

        --------------------------------------------------------
        -- Write Address 20
        -- Mem[20] = 1111
        --------------------------------------------------------
        t_Enable    <= '1';
        t_ReadWrite <= '0';
        t_Address   <= "010100";
        t_DataIn    <= "1111";

        wait for 10 ns;

        --------------------------------------------------------
        -- Read Address 20
        -- Expected: 1111
        --------------------------------------------------------
        t_ReadWrite <= '1';

        wait for 10 ns;

        --------------------------------------------------------
        -- Overwrite Address 20
        -- Mem[20] = 0011
        --------------------------------------------------------
        t_ReadWrite <= '0';
        t_DataIn    <= "0011";

        wait for 10 ns;

        --------------------------------------------------------
        -- Read Address 20
        -- Expected: 0011
        --------------------------------------------------------
        t_ReadWrite <= '1';

        wait for 10 ns;

        --------------------------------------------------------
        -- Disable Memory
        -- Expected: ZZZZ
        --------------------------------------------------------
        t_Enable <= '0';

        wait for 10 ns;

        --------------------------------------------------------
        -- Finish
        --------------------------------------------------------
        wait;

    end process;

end Behavioral;
