library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity Binary_Counter_4_Par_Load_vhdl_tb is
end Binary_Counter_4_Par_Load_vhdl_tb;

architecture Behavioral of Binary_Counter_4_Par_Load_vhdl_tb is

    signal t_A_count : unsigned(3 downto 0) := "0000";
    signal t_C_out   : std_logic;
    signal t_Data_in : unsigned(3 downto 0) := "0000";
    signal t_count   : std_logic := '0';
    signal t_load    : std_logic := '0';
    signal t_clk     : std_logic := '0';
    signal t_clear_b : std_logic := '1';

begin

    -- DUT
    UUT : entity work.Binary_Counter_4_Par_Load_vhdl
        port map (
            A_count => t_A_count,
            C_out   => t_C_out,
            Data_in => t_Data_in,
            count   => t_count,
            load    => t_load,
            clk     => t_clk,
            clear_b => t_clear_b
        );

    ------------------------------------------------------------------
    -- Clock Generation
    -- Clock Period = 10 ns
    ------------------------------------------------------------------
    clock_process : process
    begin
        while now < 160 ns loop

            t_clk <= '0';
            wait for 5 ns;

            t_clk <= '1';
            wait for 5 ns;

        end loop;

        wait;
    end process;

    ------------------------------------------------------------------
    -- Stimulus
    ------------------------------------------------------------------
    stimulus_process : process
    begin

        ----------------------------------------------------------------
        -- Initial Clear
        ----------------------------------------------------------------
        t_clear_b <= '1';
        t_count   <= '0';
        t_load    <= '0';
        t_Data_in <= "0000";

        wait for 2 ns;

        t_clear_b <= '0';
        wait for 3 ns;

        t_clear_b <= '1';

        ----------------------------------------------------------------
        -- Parallel Load
        -- Load 1010
        ----------------------------------------------------------------
        t_load    <= '1';
        t_count   <= '0';
        t_Data_in <= "1010";

        wait for 10 ns;

        ----------------------------------------------------------------
        -- Hold
        ----------------------------------------------------------------
        t_load  <= '0';
        t_count <= '0';

        wait for 10 ns;

        ----------------------------------------------------------------
        -- Count
        -- 1010 -> 1011
        ----------------------------------------------------------------
        t_count <= '1';

        wait for 10 ns;

        ----------------------------------------------------------------
        -- Count
        -- 1011 -> 1100
        ----------------------------------------------------------------
        wait for 10 ns;

        ----------------------------------------------------------------
        -- Count
        -- 1100 -> 1101
        ----------------------------------------------------------------
        wait for 10 ns;

        ----------------------------------------------------------------
        -- Hold
        ----------------------------------------------------------------
        t_count <= '0';

        wait for 10 ns;

        ----------------------------------------------------------------
        -- Parallel Load
        -- Load 1110
        ----------------------------------------------------------------
        t_load    <= '1';
        t_count   <= '0';
        t_Data_in <= "1110";

        wait for 10 ns;

        ----------------------------------------------------------------
        -- Count
        -- 1110 -> 1111
        ----------------------------------------------------------------
        t_load  <= '0';
        t_count <= '1';

        wait for 10 ns;

        ----------------------------------------------------------------
        -- Carry-out Check
        -- A_count = 1111
        -- C_out = 1
        ----------------------------------------------------------------
        wait for 5 ns;

        ----------------------------------------------------------------
        -- Overflow
        -- 1111 -> 0000
        ----------------------------------------------------------------
        wait for 5 ns;

        ----------------------------------------------------------------
        -- Hold
        ----------------------------------------------------------------
        t_count <= '0';

        wait for 10 ns;

        ----------------------------------------------------------------
        -- Load Priority Test
        -- Load = 1 and Count = 1
        -- Load should have priority
        ----------------------------------------------------------------
        t_load    <= '1';
        t_count   <= '1';
        t_Data_in <= "0101";

        wait for 10 ns;

        ----------------------------------------------------------------
        -- Hold
        ----------------------------------------------------------------
        t_load  <= '0';
        t_count <= '0';

        wait for 10 ns;

        ----------------------------------------------------------------
        -- Asynchronous Clear
        ----------------------------------------------------------------
        t_clear_b <= '0';

        wait for 5 ns;

        t_clear_b <= '1';

        ----------------------------------------------------------------
        -- Final Count
        ----------------------------------------------------------------
        t_count <= '1';

        wait for 10 ns;

        wait;

    end process;

end Behavioral;