`timescale 1ns / 1ps

module JK_Flip_Flop_2_tb;

    reg J;
    reg K;
    reg clk;

    wire Q;
    wire Q_b;

    // DUT
    JK_Flip_Flop_2 DUT (
        .J(J),
        .K(K),
        .clk(clk),
        .Q(Q),
        .Q_b(Q_b)
    );

    //--------------------------------------------------
    // Clock Generation
    // Clock Period = 10 ns
    //--------------------------------------------------
    initial
    begin
        clk = 0;

        while ($time < 160)
        begin
            #5 clk = ~clk;
        end
    end

    //--------------------------------------------------
    // Stimulus
    //--------------------------------------------------
    initial
    begin

        //------------------------------------------
        // Initial State
        //------------------------------------------
        J = 0;
        K = 0;

        #20;

        //------------------------------------------
        // Hold
        // J = 0, K = 0
        //------------------------------------------
        J = 0;
        K = 0;

        #20;

        //------------------------------------------
        // Reset
        // J = 0, K = 1
        //------------------------------------------
        J = 0;
        K = 1;

        #20;

        //------------------------------------------
        // Set
        // J = 1, K = 0
        //------------------------------------------
        J = 1;
        K = 0;

        #20;

        //------------------------------------------
        // Toggle
        // J = 1, K = 1
        //------------------------------------------
        J = 1;
        K = 1;

        #40;

        $stop;

    end

endmodule
