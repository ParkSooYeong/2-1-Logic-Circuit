`timescale 1ns / 1ps

module Mealy_Zero_Detector_tb;

    reg x_in;
    reg clock;
    reg reset;

    wire y_out;

    //--------------------------------------------------
    // DUT
    //--------------------------------------------------
    Mealy_Zero_Detector DUT (
        .x_in(x_in),
        .clock(clock),
        .reset(reset),
        .y_out(y_out)
    );

    //--------------------------------------------------
    // Clock Generation
    // Clock Period = 10 ns
    //--------------------------------------------------
    initial
    begin
        clock = 0;

        while ($time < 200)
        begin
            #5 clock = ~clock;
        end
    end

    //--------------------------------------------------
    // Stimulus
    //--------------------------------------------------
    initial
    begin

        //------------------------------------------
        // Initial State
        //------------------------------------------
        x_in  = 0;
        reset = 0;

        //------------------------------------------
        // Reset Release
        //------------------------------------------
        #2 reset = 1;

        //------------------------------------------
        // Input Sequence
        //------------------------------------------
        #10 x_in = 1;
        #20 x_in = 0;
        #10 x_in = 1;
        #10 x_in = 0;
        #2  x_in = 1;
        #2  x_in = 0;
        #26 x_in = 1;
        #20 x_in = 0;
        #20 x_in = 1;

        //------------------------------------------
        // Reset Pulse
        //------------------------------------------
        #7 reset = 0;
        #2 reset = 1;

        //------------------------------------------
        // Finish Simulation
        //------------------------------------------
        #80 $stop;

    end

endmodule
