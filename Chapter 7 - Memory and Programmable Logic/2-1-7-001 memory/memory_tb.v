`timescale 1ns/100ps

module memory_tb;

    reg Enable;
    reg ReadWrite;
    reg [5:0] Address;
    reg [3:0] DataIn;

    wire [3:0] DataOut;

    // DUT
    memory DUT (
        .Enable(Enable),
        .ReadWrite(ReadWrite),
        .Address(Address),
        .DataIn(DataIn),
        .DataOut(DataOut)
    );

    // Stimulus
    initial begin

        // Initial values
        Enable   = 1'b0;
        ReadWrite = 1'b0;
        Address  = 6'b000000;
        DataIn   = 4'b0000;

        // ---------------------------------------------------------
        // Write Address 0
        // Mem[0] = 1010
        // ---------------------------------------------------------
        #10;
        Enable    = 1'b1;
        ReadWrite = 1'b0;
        Address   = 6'b000000;
        DataIn    = 4'b1010;

        #10;

        // ---------------------------------------------------------
        // Write Address 1
        // Mem[1] = 1100
        // ---------------------------------------------------------
        Address = 6'b000001;
        DataIn  = 4'b1100;

        #10;

        // ---------------------------------------------------------
        // Write Address 10
        // Mem[10] = 0110
        // ---------------------------------------------------------
        Address = 6'b001010;
        DataIn  = 4'b0110;

        #10;

        // ---------------------------------------------------------
        // Read Address 0
        // Expected: 1010
        // ---------------------------------------------------------
        ReadWrite = 1'b1;
        Address   = 6'b000000;

        #10;

        // ---------------------------------------------------------
        // Read Address 1
        // Expected: 1100
        // ---------------------------------------------------------
        Address = 6'b000001;

        #10;

        // ---------------------------------------------------------
        // Read Address 10
        // Expected: 0110
        // ---------------------------------------------------------
        Address = 6'b001010;

        #10;

        // ---------------------------------------------------------
        // Disable Memory
        // Expected: DataOut = ZZZZ
        // ---------------------------------------------------------
        Enable = 1'b0;

        #10;

        // ---------------------------------------------------------
        // Write Address 20
        // Mem[20] = 1111
        // ---------------------------------------------------------
        Enable    = 1'b1;
        ReadWrite = 1'b0;
        Address   = 6'b010100;
        DataIn    = 4'b1111;

        #10;

        // ---------------------------------------------------------
        // Read Address 20
        // Expected: 1111
        // ---------------------------------------------------------
        ReadWrite = 1'b1;

        #10;

        // ---------------------------------------------------------
        // Overwrite Address 20
        // Mem[20] = 0011
        // ---------------------------------------------------------
        ReadWrite = 1'b0;
        DataIn    = 4'b0011;

        #10;

        // ---------------------------------------------------------
        // Read Address 20
        // Expected: 0011
        // ---------------------------------------------------------
        ReadWrite = 1'b1;

        #10;

        // ---------------------------------------------------------
        // Disable Memory
        // ---------------------------------------------------------
        Enable = 1'b0;

        #10;

        $finish;

    end

endmodule
